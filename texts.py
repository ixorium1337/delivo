def calc_result(res) -> str:
    text = (
        "🧾 <b>Предварительный расчёт:</b>\n\n"
        f"• Товар: <b>{res.price_cny:.2f} ¥</b> (~{res.goods_rub:.2f} ₽)\n"
        f"• Город прибытия: <b>{res.city_name}</b> ({res.delivery_type})\n"
        f"• Доставка после прибытия: <b>{escape(res.delivery_method)}</b>\n"
        f"• Вес посылки: <b>{res.weight_kg:.2f} кг</b>\n"
        f"• Карго до {res.city_name}: <b>{res.delivery_usd:.2f} $</b> (~{res.delivery_rub:.2f} ₽)\n"
        f"• Комиссия сервиса: <b>{res.service_fee_rub:.2f} ₽</b> (4%, мин. 400 ₽)\n\n"
        "━━━━━━━━━━━━━━━\n"
        f"💰 <b>ПРЕДВАРИТЕЛЬНО: {res.total_rub:.2f} ₽</b>\n"
        "━━━━━━━━━━━━━━━\n"
        "\n⚠️ <b>Сумма не является окончательной.</b> Она может незначительно измениться после фактического взвешивания и оформления. "
        f"Доставка из {res.city_name} в ваш город через {escape(res.delivery_method)} оплачивается отдельно и в эту сумму не входит.\n"
    )
    if res.consolidated_info:
        info = res.consolidated_info
        text += (
            "\n📦 <b>Статус сборного груза (Волгоград):</b>\n"
            f"• В текущей коробке собрано: <b>{info['current']:.2f} / {info['target']:.2f} кг</b>\n"
        )
        if info["remaining"] > 0:
            text += f"• До отправки партии в РФ осталось: <b>{info['remaining']:.2f} кг</b>\n"
        else:
            text += "• <i>Минимальный объём набран! Партия готовится к отправке.</i>\n"
    return text + f"\n<i>Курсы: 1 ¥ = {res.cny_rate} ₽ | 1 $ = {res.usd_rate} ₽</i>"


