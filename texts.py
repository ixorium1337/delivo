def user_orders(orders: list[dict], shipment_lookup=None) -> str:
    status_map = ORDER_STATUS_LABELS
    text = "📋 <b>История ваших заказов:</b>\n\n"
    for order in orders:
        status = status_map.get(order["status"], "Неизвестный статус")
        text += (
            "━━━━━━━━━━━━━━━━━━\n"
            f"<b>Тикет #{order['order_id']}</b> ({escape(order['city_name'])}, {order['weight_kg']} кг)\n"
            f"• 📅 Дата: <b>{escape(str(order.get('created_at', 'Не указана')))}</b>\n"
            f"• Статус: <b>{status}</b>\n"
            f"• Сумма: <b>{order['total_rub']:.2f} ₽</b>\n"
            f"• 🚚 Доставка дальше: <b>{escape(order.get('delivery_method') or 'не указана')}</b>\n"
        )
        if order.get("status_message"):
            text += f"• 📣 Обновление: <b>{escape(order['status_message'])}</b>\n"
        if order["status"] != "rejected":
            trackers = order.get("trackers", [])
            if trackers:
                text += f"• 📍 Трек-номера товара: <code>{escape(', '.join(trackers))}</code>\n"
            else:
                text += "• 📍 Трек-номер товара: <i>ожидает присвоения</i>\n"
        elif order.get("reject_reason"):
            text += f"• ⚠️ Причина отказа: <i>{escape(order['reject_reason'])}</i>\n"
        shipment = order.get("shipment")
        if not shipment and order.get("shipment_id") and shipment_lookup:
            shipment = shipment_lookup(order["shipment_id"])
        if shipment:
            text += (
                f"• 🚚 Отправление #{shipment['id']}: <b>{escape(shipment['name'])}</b>\n"
                f"• 📦 Карго-номер: <code>{escape(shipment['track_number'])}</code>\n"
                f"• Статус отправления: <b>{escape(shipment_status_label(shipment['status']))}</b>\n"
            )
            if shipment.get("arrived_at"):
                text += f"• 📍 Прибыло в {escape(order['city_name'])}: <b>{escape(shipment['arrived_at'])}</b>\n"
        if order.get("sent_to_client_at"):
            text += f"• 📤 Отправлен клиенту: <b>{escape(order['sent_to_client_at'])}</b>\n"
        if order.get("delivered_at"):
            text += f"• 📬 Доставлен: <b>{escape(order['delivered_at'])}</b>\n"
    return text + "━━━━━━━━━━━━━━━━━━"

